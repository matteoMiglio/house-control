// Writes macos/Sources/HouseControl/LucideIcons.swift: the Lucide icons the web UI uses
// (web/src/ui/icons.js), as SVG for the native controls, so both draw exactly the same ones.
// Run with Node from the repository: node scripts/lucide-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ICONS } from '../web/src/ui/icons.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const { version } = JSON.parse(readFileSync(`${root}web/node_modules/lucide/package.json`, 'utf8'));
const escape = (s) => s.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
const svg = (node) => node.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('');

const entries = Object.entries(ICONS)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, node]) => `        "${name}": "${escape(svg(node))}",`);

writeFileSync(`${root}macos/Sources/HouseControl/LucideIcons.swift`, `// Generated by scripts/lucide-icons.mjs from Lucide ${version}: do not edit.

/// The SVG elements of every icon the web UI draws, by the name web/src/ui/icons.js gives it.
enum LucideIcons {
    static let elements: [String: String] = [
${entries.join('\n')}
    ]
}
`);
console.log(`${entries.length} icons, Lucide ${version}`);
